local function routeStats(route)
    local out = { craftSteps=0, trainerSteps=0, estimatedSteps=0, keepSteps=0, sourceRequirements=0, gaps={} }
    local previousTarget = nil
    for _, step in ipairs(route and route.steps or {}) do
        if step.kind == "craft" then
            out.craftSteps = out.craftSteps + 1
            if step.estimated then out.estimatedSteps = out.estimatedSteps + 1 end
            if step.keep then out.keepSteps = out.keepSteps + 1 end
            if step.sourceRequirement then out.sourceRequirements = out.sourceRequirements + 1 end
            if previousTarget and tonumber(step.skillMin) and tonumber(step.skillMin) > previousTarget then
                out.gaps[#out.gaps + 1] = { fromSkill=previousTarget, toSkill=tonumber(step.skillMin), evidence=EVIDENCE }
            end
            previousTarget = math.max(previousTarget or 0, tonumber(step.skillTarget) or 0)
        elseif step.kind == "train" then
            out.trainerSteps = out.trainerSteps + 1
        end
    end
    return out
end

for _, modes in pairs(JLP.data.professionResearchRoutes.professions) do
    for _, route in pairs(modes) do route.stats = routeStats(route) end
end
